use super::*;
use crate::generation::{AdmissionRefusal, Disposition, Terminal};
use liteinst2::scanner::InstructionScanner;
use liteinst2::trampoline::{ExecutableTrampoline, TrampolinePlan};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Mutex, mpsc};
use std::time::Duration;

const A: FunctionId = FunctionId(11);
const B: FunctionId = FunctionId(12);
const WAIT: Duration = Duration::from_secs(5);
static CODE: [u8; 8] = [0xb8, 42, 0, 0, 0, 0x90, 0x90, 0xc3];
static COUNTS: [AtomicUsize; 3] = [const { AtomicUsize::new(0) }; 3];

#[derive(Clone, Copy, Eq, PartialEq)]
pub(super) enum Phase {
    BeforeReservation,
    AfterReservation,
}
pub(super) struct Pause {
    pc: u64,
    phase: Phase,
    entered: mpsc::Sender<()>,
    release: Mutex<mpsc::Receiver<()>>,
}
pub(super) fn pause(binding: &Binding, pc: u64, phase: Phase) {
    // Take exactly once, release the setup mutex before waiting. The same
    // real callback path is used; only these test scheduling points are added.
    let pause = {
        let mut guard = binding.pause.lock().unwrap();
        if guard
            .as_ref()
            .is_some_and(|p| p.pc == pc && p.phase == phase)
        {
            guard.take()
        } else {
            None
        }
    };
    if let Some(pause) = pause {
        pause.entered.send(()).unwrap();
        pause.release.lock().unwrap().recv_timeout(WAIT).unwrap();
    }
}
fn hold(c: &DataFlagSession, phase: Phase) -> (mpsc::Receiver<()>, mpsc::Sender<()>) {
    hold_pc(c, phase, CODE.as_ptr() as u64)
}
fn hold_pc(c: &DataFlagSession, phase: Phase, pc: u64) -> (mpsc::Receiver<()>, mpsc::Sender<()>) {
    let (entered, receive) = mpsc::channel();
    let (release, wait) = mpsc::channel();
    *c.binding.pause.lock().unwrap() = Some(Pause {
        pc,
        phase,
        entered,
        release: Mutex::new(wait),
    });
    (receive, release)
}
unsafe extern "C" fn a(_: *mut HookContext) {
    COUNTS[0].fetch_add(1, Ordering::SeqCst);
}
unsafe extern "C" fn b(_: *mut HookContext) {
    COUNTS[1].fetch_add(1, Ordering::SeqCst);
}
unsafe extern "C" fn mandatory(_: *mut HookContext) {
    COUNTS[2].fetch_add(1, Ordering::SeqCst);
}
fn counts() -> [usize; 3] {
    std::array::from_fn(|i| COUNTS[i].load(Ordering::SeqCst))
}
fn config(k: usize) -> Config {
    Config {
        retained_per_function: k,
        max_inflight: 4,
        max_invocations: 16,
    }
}
fn fixture() -> (DataFlagSession, u64, Vec<u8>) {
    for counter in &COUNTS {
        counter.store(0, Ordering::SeqCst);
    }
    let pc = CODE.as_ptr() as u64;
    let c = DataFlagSession::new(
        73,
        &[
            PointSpec {
                pc,
                group: 0,
                function: Some(A),
                callback: a,
            },
            PointSpec {
                pc: pc + 5,
                group: 0,
                function: Some(B),
                callback: b,
            },
            PointSpec {
                pc: pc + 6,
                group: 0,
                function: None,
                callback: mandatory,
            },
        ],
        frontend::Limits {
            epochs: 4,
            threads: 8,
            depth: 4,
            records_per_epoch: 16,
            actions: 32,
        },
    )
    .unwrap();
    let scan = InstructionScanner::default().scan(&CODE, pc).unwrap();
    let plan =
        TrampolinePlan::from_controlled_actions(&scan, pc, pc + CODE.len() as u64, &c.actions())
            .unwrap();
    let image = ExecutableTrampoline::allocate(&plan).unwrap();
    // The existing executable allocator retains this image and controls for
    // process lifetime. All old images remain live in the same-PC refusal test.
    let address = image.address();
    // SAFETY: the published RX image owns all code_len initialized bytes for
    // process lifetime; this immutable whole-image copy is an expected value.
    let bytes =
        unsafe { std::slice::from_raw_parts(address as *const u8, image.code_len()) }.to_vec();
    drop(image);
    (c, address, bytes)
}
fn unchanged(address: u64, before: &[u8]) {
    // SAFETY: fixture() retains the exact published code extent for process life.
    let after = unsafe { std::slice::from_raw_parts(address as *const u8, before.len()) };
    assert_eq!(
        after, before,
        "data-flag operations never rewrite generated bytes"
    );
}
fn invoke(address: u64) {
    // SAFETY: fixture() emitted only MOV/NOP/NOP/RET and full-state observing
    // calls, in a retained RX allocation with the normal extern-C return ABI.
    let call: unsafe extern "C" fn() -> u32 = unsafe { std::mem::transmute(address as usize) };
    assert_eq!(unsafe { call() }, 42);
}
fn worker(c: &DataFlagSession, address: u64) -> std::thread::JoinHandle<PointDiagnostics> {
    let binding = Arc::clone(&c.binding);
    std::thread::spawn(move || {
        // Same production attachment function, without handing a controller or
        // writer to the worker. A small private helper is shared below.
        let thread = attach_binding(&binding).unwrap();
        invoke(address);
        thread.diagnostics().unwrap()
    })
}
fn rows(c: &DataFlagSession, epoch: Epoch) -> Vec<frontend::RecordObservation> {
    c.report(epoch).unwrap().unwrap().records().collect()
}
fn point_rows(c: &DataFlagSession, epoch: Epoch, function: FunctionId) -> usize {
    rows(c, epoch)
        .iter()
        .filter(|r| r.record.admission.function == function)
        .count()
}

// One native test owns the counters and runs a fixed straight-line fixture.
// No ignored tests, statistical races, stress loops or optional native branches.
// The enclosing existing bounded test/helper command remains the run authority.
#[test]
fn actual_managed_points_force_close_rearm_k_groups_and_wrong_owner() {
    // Acquired old owner, paused before reservation: rearm must close it and
    // the resumed A must refuse. B, reached afterward, belongs to the new owner.
    let (mut c, address, code) = fixture();
    let old = c.stage(config(8)).unwrap();
    let arm = c.arm(old).unwrap();
    assert_eq!(c.complete(&arm), Ok(Visibility::Eventual));
    assert_eq!(
        c.admission_boundary(&arm),
        Ok(AdmissionBoundary::Current(old))
    );
    let (entered, release) = hold(&c, Phase::BeforeReservation);
    let job = worker(&c, address);
    entered.recv_timeout(WAIT).unwrap();
    let new = c.stage(config(8)).unwrap();
    let next = c.arm(new).unwrap();
    assert_eq!(c.complete(&arm), Err(Refusal::StaleGeneration));
    assert_eq!(c.complete(&next), Ok(Visibility::Eventual));
    c.close_and_drain(old).unwrap();
    assert!(rows(&c, old).is_empty());
    release.send(()).unwrap();
    let diagnostics = job.join().unwrap();
    assert_eq!(diagnostics.refusals, 1);
    assert_eq!(
        diagnostics.last_refusal,
        Some(PointOutcome::AdmissionRefused(
            frontend_tls::BridgeError::Entry(frontend::EntryError::Generation(
                AdmissionRefusal::EpochClosed
            ))
        ))
    );
    assert!(
        matches!(diagnostics.last, Some(PointOutcome::Completed { completion, .. }) if completion.admission.generation.get() == new.0)
    );
    assert_eq!(counts(), [0, 1, 1]);
    c.close_and_drain(new).unwrap();
    assert_eq!(point_rows(&c, new, A), 0);
    assert_eq!(point_rows(&c, new, B), 1);
    unchanged(address, &code);
    drop(c);

    // Reserved old callback, paused before work: rearm cannot drain it. After
    // its real callback returns, all terminal/payload identities stay old.
    let (mut c, address, code) = fixture();
    let old = c.stage(config(1)).unwrap();
    c.arm(old).unwrap();
    let (entered, release) = hold(&c, Phase::AfterReservation);
    let job = worker(&c, address);
    entered.recv_timeout(WAIT).unwrap();
    let new = c.stage(config(8)).unwrap();
    let ticket = c.arm(new).unwrap();
    assert_eq!(c.complete(&ticket), Ok(Visibility::Eventual));
    assert!(c.close_and_drain(old).is_err());
    assert!(c.report(old).unwrap().is_none());
    release.send(()).unwrap();
    assert_eq!(job.join().unwrap().refusals, 0);
    c.close_and_drain(old).unwrap();
    let old_rows = rows(&c, old);
    assert_eq!(old_rows.len(), 1);
    assert_eq!(old_rows[0].record.admission.function, A);
    assert_eq!(
        old_rows[0].record.terminal,
        Some(Terminal::Completed {
            value: 0,
            disposition: Disposition::Retained { rank: 0 }
        })
    );
    assert_eq!(
        old_rows[0].payload.unwrap().admission,
        old_rows[0].record.admission
    );
    let request = DeactivationRequest {
        generation: c.owner(old).unwrap().generation(),
        function: A,
    };
    let before: Vec<_> = c.actions().iter().map(|a| a.control.is_enabled()).collect();
    c.deactivate(request).unwrap();
    assert_eq!(
        c.actions()
            .iter()
            .map(|a| a.control.is_enabled())
            .collect::<Vec<_>>(),
        before
    );
    assert_eq!(
        c.complete(&ticket),
        Ok(Visibility::Eventual),
        "stale K request cannot invalidate or mutate new state"
    );
    let attachment = c.attach_current_thread().unwrap();
    invoke(address);
    assert_eq!(counts(), [2, 2, 2]);
    drop(attachment);
    c.close_and_drain(new).unwrap();
    assert_eq!((point_rows(&c, new, A), point_rows(&c, new, B)), (1, 2));
    unchanged(address, &code);
    drop(c);

    // Independent members share one real generated image. Closing A does not
    // close B or mandatory work, and planner clones cannot change any flag.
    let (mut c, address, code) = fixture();
    let epoch = c.stage(config(1)).unwrap();
    c.arm(epoch).unwrap();
    let (entered, release) = hold_pc(&c, Phase::BeforeReservation, CODE.as_ptr() as u64 + 5);
    let job = worker(&c, address);
    entered.recv_timeout(WAIT).unwrap();
    // The real A callback has completed at K; B acquired its still-open owner
    // but has not reserved. The first controller update must disable A alone.
    let actions = c.actions();
    for action in &actions {
        assert!(action.control.try_set_enabled(false).is_err());
    }
    assert_eq!(
        c.scan_closed().unwrap(),
        1,
        "the existing bounded scan finds A without a notification queue"
    );
    assert!(!actions[0].control.is_enabled());
    assert!(actions[1].control.is_enabled());
    assert!(actions[2].control.is_enabled());
    release.send(()).unwrap();
    let completed_b = job.join().unwrap();
    assert_eq!(completed_b.refusals, 0);
    let Some(PointOutcome::Completed { completion, .. }) = completed_b.last else {
        panic!("B must complete")
    };
    assert_eq!(completion.admission.function, B);
    let attachment = c.attach_current_thread().unwrap();
    invoke(address);
    assert_eq!(counts(), [1, 1, 2]);
    assert_eq!(
        attachment.diagnostics().unwrap().last_refusal,
        Some(PointOutcome::AdmissionRefused(
            frontend_tls::BridgeError::Entry(frontend::EntryError::Generation(
                AdmissionRefusal::FunctionClosed
            ))
        ))
    );
    c.deactivate(completion.deactivate.unwrap()).unwrap();
    assert!(!actions[0].control.is_enabled() && !actions[1].control.is_enabled());
    assert!(actions[2].control.is_enabled());
    let off = c.disarm(epoch).unwrap();
    assert_eq!(c.complete(&off), Ok(Visibility::Eventual));
    assert_eq!(
        c.admission_boundary(&off),
        Ok(AdmissionBoundary::Closed(epoch))
    );
    invoke(address);
    assert_eq!(counts(), [1, 1, 3]);
    drop(attachment);
    c.close_and_drain(epoch).unwrap();
    assert_eq!(rows(&c, epoch).len(), 2);
    unchanged(address, &code);
    drop(c);

    // An old image at the same PCs must not use another installation's TLS
    // owners, even when both logical maps and caller install numbers match.
    let (mut old, old_image, old_code) = fixture();
    let old_epoch = old.stage(config(8)).unwrap();
    old.arm(old_epoch).unwrap();
    let (mut new, new_image, new_code) = fixture();
    let new_epoch = new.stage(config(8)).unwrap();
    let foreign_ticket = new.arm(new_epoch).unwrap();
    assert_eq!(old.complete(&foreign_ticket), Err(Refusal::StaleGeneration));
    let attachment = new.attach_current_thread().unwrap();
    invoke(old_image);
    assert_eq!(
        attachment.diagnostics().unwrap(),
        PointDiagnostics {
            last: Some(PointOutcome::BindingRefused),
            last_refusal: Some(PointOutcome::BindingRefused),
            refusals: 2,
        }
    );
    assert_eq!(counts(), [0, 0, 1]);
    drop(attachment);
    old.close_and_drain(old_epoch).unwrap();
    new.close_and_drain(new_epoch).unwrap();
    assert!(rows(&old, old_epoch).is_empty() && rows(&new, new_epoch).is_empty());
    unchanged(old_image, &old_code);
    unchanged(new_image, &new_code);
}
