#[derive(Clone, Copy, Eq, PartialEq)]
pub(super) enum Mode {
    Work,
    DropSampled,
    DropClosed,
}
impl Mode {
    pub(super) fn parse(value: &str) -> Option<Self> {
        match value {
            "normal-work" => Some(Self::Work),
            "normal-drop-sampled" => Some(Self::DropSampled),
            "normal-drop-closed" => Some(Self::DropClosed),
            _ => None,
        }
    }
}

const INSTALL: u64 = 0x6e6f_7201;
const NORMAL_CONTRACT: NormalLeafContract = NormalLeafContract {
    single_external_entry: true,
    ordinary_call_ret_only: true,
    no_active_cet: true,
};
const CONFIG: Config = Config {
    retained_per_function: 2,
    max_inflight: 1,
    max_invocations: 8,
};

fn input() -> [[u8; 96]; 8] {
    std::array::from_fn(|i| {
        let mut bytes = [0xa5; 96];
        bytes[16..80].copy_from_slice(&cases::input(CASES[i]));
        bytes[80..].fill(0x5a);
        bytes
    })
}

fn requests(input: &[[u8; 96]; 8], pair: usize) -> [Request; 2] {
    std::array::from_fn(|i| Request {
        data: input[pair * 2 + i][16..].as_ptr(),
        bound: CASES[pair * 2 + i].bound as u64,
    })
}

// Qualification custody: complete source pages and all generated executable bytes.
// This is a consumer check; the normal runtime promises no source or input scan.
unsafe fn immutable(spans: &[(u64, Vec<u8>)]) {
    for (address, expected) in spans {
        // SAFETY: sealed process-lived owners and continuous no-writer/no-unmap
        // contract; this comparison does not establish mapping lifetime itself.
        assert_eq!(
            unsafe { std::slice::from_raw_parts(*address as usize as *const u8, expected.len()) },
            expected,
            "complete normal source/generated bytes"
        );
    }
}

fn publish(prep: NormalSitePreparation) -> rapid_profiler::frontend_native::InstalledNormalSite {
    single_main();
    let planned = prep.plan();
    let originals = planned.plan().originals();
    assert_eq!(originals.len(), 1);
    let source = AddressRange::new(originals[0].address, originals[0].bytes.len()).unwrap();
    assert_eq!(source.start() % 4096, 0);
    assert!(matches!(source.len(), 4096 | 8192));
    let mut ranges = vec![source];
    ranges.extend(
        planned
            .plan()
            .steps()
            .iter()
            .flat_map(|p| p.parts().allocations.iter().map(|a| a.range)),
    );
    // This process has one actual thread and no subject caller, saved resume,
    // signal handler, writer or live invocation. Every baseline CALL returned.
    let mut exclusive = &prep;
    protect(source, libc::PROT_READ | libc::PROT_WRITE).unwrap();
    let alias = unsafe { WritableAlias::new(source, source.start() as usize as *mut u8) }.unwrap();
    let result = {
        let mut lease =
            unsafe { QuiescenceLease::new(&mut exclusive, planned.plan().identity(), ranges) };
        let result = unsafe {
            planned.publish_with(&[alias], &mut lease, || {
                protect(source, libc::PROT_READ | libc::PROT_EXEC)
            })
        };
        if result.is_ok() {
            assert!(!lease.is_poisoned());
        }
        result
    };
    let (installed, receipt) = match result {
        Ok(pair) => pair,
        Err(error) => {
            eprintln!("normal publication FAILED: {error:?}");
            std::process::abort();
        }
    };
    // SAFETY: actual complete transaction and RX source under sole-thread
    // exclusion. Seal retains every code/control/source owner for process life.
    unsafe { prep.seal(installed, receipt) }.unwrap()
}

fn pending(n: u64) -> NormalTotals {
    assert!(matches!(n, 2 | 4 | 6 | 8));
    NormalTotals {
        entered: n,
        ret_observed: n,
        confirmed: n - 1,
        completed: (n - 1).min(4),
        unsampled: (n - 1).saturating_sub(4),
    }
}
fn completed() -> NormalTotals {
    NormalTotals {
        entered: 8,
        ret_observed: 8,
        confirmed: 8,
        completed: 4,
        unsampled: 4,
    }
}

struct Done {
    values: [u64; 8],
    batch: NormalBatch,
    tid: u64,
}

pub(super) fn run(
    candidate: &Path,
    trusted: &Path,
    elf_va: u64,
    length: u64,
    caller_candidate: &Path,
    caller_trusted: &Path,
    mode: Mode,
) {
    single_main();
    let cpu = pin(None);
    let bytes = expected_file(candidate, trusted);
    let caller_bytes = expected_file(caller_candidate, caller_trusted);
    // SAFETY: separately pinned complete compiler outputs, no dependency or
    // constructor, no source/alias writer, unload, signals, CET or nonlocal exit.
    // The selected production function has its independently authenticated full
    // extent. Every actual input read is inside the immutable guarded object.
    let mut calling = unsafe { CallerOwner::load(caller_candidate, &caller_bytes) }.unwrap();
    let caller_entry = calling.entry();
    let selection =
        TrustedFunctionSelection::new(&bytes, elf_va, usize::try_from(length).unwrap(), LABEL)
            .unwrap();
    let owner =
        unsafe { LoadedNormalLeaf::load_selected(candidate, &selection, NORMAL_CONTRACT) }.unwrap();
    let entry = owner.entry();
    let returns: BTreeSet<_> = owner.certificate().returns().iter().copied().collect();
    let expected_input = input();
    let input = Arc::new(expected_input);
    let mut originals = [0_u64; 8];
    for pair in 0..4 {
        let mut results = [u64::MAX; 2];
        let reqs = requests(&input, pair);
        // SAFETY: unpublished original scalar, valid immutable inputs, real C
        // caller and normal CALL/RET. No profiler call is made inside caller.c.
        let sum = unsafe { calling.invoke(entry, &reqs, &mut results) };
        assert_eq!(sum, results[0] + results[1]);
        for j in 0..2 {
            assert_eq!(results[j], cases::scalar(CASES[pair * 2 + j]));
            originals[pair * 2 + j] = results[j];
        }
        assert_eq!(*input, expected_input);
        calling.verify().unwrap();
        owner.verify_original().unwrap();
    }
    let prep = NormalSitePreparation::new_whole_function(owner, identity(entry)).unwrap();
    assert_eq!(
        prep.role_pcs().collect::<Vec<_>>(),
        std::iter::once(entry)
            .chain(returns.iter().copied())
            .collect::<Vec<_>>()
    );
    let mut spans: Vec<_> = prep
        .plan()
        .plan()
        .final_bytes()
        .iter()
        .map(|s| (s.address, s.bytes.clone()))
        .collect();
    spans.extend(
        prep.plan()
            .images()
            .iter()
            .map(|i| (i.address(), i.bytes().to_vec())),
    );
    let (caller_page, caller_source) = calling.source();
    spans.push((caller_page, caller_source.to_vec()));
    let spans = Arc::new(spans);
    let site = publish(prep);
    unsafe { immutable(&spans) };
    let mut prepared = PreparedNormalController::new(
        site,
        INSTALL,
        FUNCTION,
        Limits {
            epochs: if mode == Mode::Work { 2 } else { 1 },
            threads: 1,
            depth: 1,
            records_per_epoch: 8,
            actions: if mode == Mode::Work { 4 } else { 2 },
        },
    )
    .unwrap();
    if mode != Mode::Work {
        lifecycle::run(
            prepared,
            mode,
            &mut calling,
            lifecycle::Inputs {
                cpu,
                entry,
                caller_entry,
                caller_path: caller_candidate.to_owned(),
                caller_bytes,
                input,
                expected_input,
                spans,
                originals,
            },
        );
        return;
    }
    let first = prepared.stage(CONFIG).unwrap();
    let second = prepared.stage(CONFIG).unwrap();
    let generations = [first.generation().get(), second.generation().get()];
    assert!(generations[0] > 0 && generations[1] > generations[0]);
    // SAFETY: complete publication, pristine metadata and no active subject.
    let (mut controller, client) = unsafe { prepared.activate_concurrent() }.unwrap();
    controller.arm(&first).unwrap();
    let (park_tx, park_rx) = mpsc::sync_channel(1);
    let (resume_tx, resume_rx) = mpsc::sync_channel(1);
    let worker_input = Arc::clone(&input);
    let worker_spans = Arc::clone(&spans);
    let caller_path = caller_candidate.to_owned();
    let handle = joined_task::spawn(move || {
        pin(Some(cpu));
        let tid = unsafe { libc::syscall(libc::SYS_gettid) } as u64;
        assert_ne!(tid, u64::from(std::process::id()));
        // The loader retains the same immutable helper; the main copy remains
        // process-lived. Only this worker invokes the installed subject.
        let mut calling = unsafe { CallerOwner::load(&caller_path, &caller_bytes) }.unwrap();
        assert_eq!(calling.entry(), caller_entry);
        let mut attached =
            unsafe { client.attach(1, stack(), IntervalJournal::allocate()) }.unwrap();
        let mut values = [0_u64; 8];
        for pair in 0..4 {
            let mut results = [u64::MAX; 2];
            let reqs = requests(&worker_input, pair);
            // One application helper call contains two real subject CALLs. No
            // gate arm, prepared invocation, SDK call or checkpoint occurs there.
            let sum = unsafe { calling.invoke(entry, &reqs, &mut results) };
            assert_eq!(sum, results[0] + results[1]);
            for j in 0..2 {
                assert_eq!(results[j], originals[pair * 2 + j]);
                values[pair * 2 + j] = results[j];
            }
            assert_eq!(*worker_input, expected_input);
            calling.verify().unwrap();
            unsafe { immutable(&worker_spans) };
            let n = (pair as u64 + 1) * 2;
            assert_eq!(attached.totals().unwrap(), pending(n));
            if pair < 3 {
                park_tx.send((n, attached.totals().unwrap())).unwrap();
                resume_rx
                    .recv_timeout(WAIT)
                    .expect("normal caller controller handshake");
            }
        }
        // Full consumer checks precede the unsafe assertion that every call
        // returned. A failure above never acknowledges or exposes the last pair.
        assert_eq!(*worker_input, expected_input);
        calling.verify().unwrap();
        unsafe { immutable(&worker_spans) };
        let batch = unsafe { attached.checkpoint_after_returns() }
            .unwrap()
            .expect("eight actual returned calls");
        assert_eq!(attached.totals().unwrap(), completed());
        assert!(
            unsafe { attached.checkpoint_after_returns() }
                .unwrap()
                .is_none()
        );
        assert_eq!(attached.detach().unwrap(), completed());
        Done { values, batch, tid }
    });
    let mut worker = Worker {
        resume: Some(resume_tx),
        handle: Some(handle),
    };
    assert_eq!(park_rx.recv_timeout(WAIT).unwrap(), (2, pending(2)));
    controller.disarm(&first).unwrap();
    assert!(
        controller.report(&first).unwrap().is_none(),
        "last A receipt retained after actual C helper return until acknowledgement"
    );
    controller.arm(&second).unwrap();
    worker.resume.as_ref().unwrap().send(()).unwrap();
    assert_eq!(park_rx.recv_timeout(WAIT).unwrap(), (4, pending(4)));
    let first_report = controller
        .report(&first)
        .unwrap()
        .expect("next entry confirmed original A");
    assert!(controller.report(&second).unwrap().is_none());
    worker.resume.as_ref().unwrap().send(()).unwrap();
    assert_eq!(park_rx.recv_timeout(WAIT).unwrap(), (6, pending(6)));
    controller.disarm(&second).unwrap();
    let second_report = controller
        .report(&second)
        .unwrap()
        .expect("B sampled records complete; FunctionClosed receipt still retained");
    worker.resume.as_ref().unwrap().send(()).unwrap();
    let done = worker.join();
    assert_eq!(Arc::strong_count(&input), 1, "actual calling worker joined");
    assert_eq!(Arc::strong_count(&spans), 1);
    assert_eq!(*input, expected_input);
    unsafe { immutable(&spans) };
    calling.verify().unwrap();
    validate(&done, entry, &returns, caller_entry, generations, originals);
    let rows: Vec<_> = done.batch.records().iter().map(|r| r.raw).collect();
    check_report(&first_report, &rows[..2], generations[0], 0);
    check_report(&second_report, &rows[2..4], generations[1], 2);
    let history = controller.history().unwrap();
    assert_eq!(history.current, None);
    // Removal clears the current generation; it does not deactivate this
    // mandatory group's historical enabled bit or its physical callbacks.
    assert_eq!(history.enabled, [true]);
    assert_eq!(history.actions.len(), 4);
    for (i, action) in history.actions.iter().enumerate() {
        assert_eq!(action.generation.get(), generations[i / 2]);
        assert_eq!(
            action.kind,
            if i % 2 == 0 {
                rapid_profiler::frontend::ActionKind::Published
            } else {
                rapid_profiler::frontend::ActionKind::Removed
            }
        );
        assert_eq!(
            action.current.map(|g| g.get()),
            (i % 2 == 0).then_some(generations[i / 2])
        );
        assert_eq!(action.function, None);
        assert_eq!(action.group, None);
    }
    single_main();
    println!(
        "ordinal,case,bound,value,owner,generation,invocation,history_prefix,ret_offset,caller_continuation,ack,start_ticks,end_ticks,start_aux,end_aux"
    );
    for (i, record) in done.batch.records().iter().enumerate() {
        let (owner, generation, invocation) = match record.raw.owner {
            RawIntervalOwner::Sampled {
                generation,
                invocation,
            } => ("sampled", generation, invocation.to_string()),
            RawIntervalOwner::FunctionClosed { generation } => {
                ("closed", generation, String::new())
            }
            RawIntervalOwner::Removed { generation } => ("removed", generation, String::new()),
            _ => unreachable!(),
        };
        println!(
            "{},{},{},{},{},{},{},{},{},{},{},{},{},{},{}",
            record.raw.ordinal,
            CASES[i].name,
            CASES[i].bound,
            done.values[i],
            owner,
            generation,
            invocation,
            record.history_prefix,
            record.raw.return_pc - entry,
            record.return_word - caller_entry,
            if i == 7 { "checkpoint" } else { "next-entry" },
            record.raw.start.ticks,
            record.raw.end.ticks,
            record.raw.start.aux,
            record.raw.end.aux
        );
    }
    println!(
        "normal-work complete original_calls=8 installed_calls=8 caller_sites=2 next_entry_acknowledgements=7 checkpoint_acknowledgements=1 sampled=4 closed=2 removed=2 generations=2 events=16 journal_words=512 reports=2 worker_joins=1"
    );
}

fn validate(
    done: &Done,
    entry: u64,
    returns: &BTreeSet<u64>,
    caller: u64,
    generations: [u64; 2],
    originals: [u64; 8],
) {
    let batch = &done.batch;
    assert_eq!(done.values, originals);
    assert_eq!(batch.pid(), std::process::id());
    assert_eq!(batch.tid(), done.tid);
    assert_eq!(batch.registration(), 1);
    assert_eq!(batch.install(), INSTALL);
    assert_eq!(batch.function(), FUNCTION);
    assert_eq!(batch.number(), 1);
    assert_eq!(batch.totals(), (NormalTotals::default(), completed()));
    assert_eq!(batch.completed_sequences(), (0, 4));
    assert_eq!(batch.next_ordinal(), 9);
    assert_eq!(batch.records().len(), 8);
    assert_eq!(batch.journal().len(), 512);
    assert_eq!(&batch.journal()[..4], &[16, 0, done.tid, 0]);
    assert!(batch.journal()[4 + 16 * 7..].iter().all(|&n| n == 0));
    let mut return_pcs = BTreeSet::new();
    for (i, record) in batch.records().iter().enumerate() {
        let ordinal = i as u64 + 1;
        assert_eq!(record.raw.ordinal, ordinal);
        assert_eq!(record.raw.entry_pc, entry);
        assert!(returns.contains(&record.raw.return_pc));
        return_pcs.insert(record.raw.return_pc);
        assert_eq!(record.entry_rsp % 16, 8);
        assert_eq!(record.return_word, caller + [30, 48][i % 2]);
        assert_eq!(
            record.acknowledgement,
            if i == 7 {
                NormalAcknowledgement::CallerCheckpoint
            } else {
                NormalAcknowledgement::NextEntry {
                    ordinal: ordinal + 1,
                }
            }
        );
        assert!(
            record.raw.elapsed_ticks().is_some(),
            "pinned raw endpoint consistency, not accuracy"
        );
        let (kind, generation, inv, prefix, reason, owner) = if i < 4 {
            let g = generations[i / 2];
            (
                1,
                g,
                i as u64 % 2 + 1,
                if i < 2 { 1 } else { 3 },
                0,
                RawIntervalOwner::Sampled {
                    generation: g,
                    invocation: i % 2,
                },
            )
        } else if i < 6 {
            (
                3,
                generations[1],
                0,
                3,
                3,
                RawIntervalOwner::FunctionClosed {
                    generation: generations[1],
                },
            )
        } else {
            (
                3,
                generations[1],
                0,
                4,
                2,
                RawIntervalOwner::Removed {
                    generation: generations[1],
                },
            )
        };
        assert_eq!(record.raw.owner, owner);
        assert_eq!(record.history_prefix, prefix);
        let bits = inv | (prefix << 13) | (reason << 22);
        let at = 4 + i * 14;
        assert_eq!(
            &batch.journal()[at..at + 7],
            &[
                kind,
                ordinal,
                entry,
                record.entry_rsp,
                record.return_word,
                generation,
                bits
            ]
        );
        assert_eq!(
            &batch.journal()[at + 7..at + 14],
            &[
                kind + 1,
                ordinal,
                record.raw.return_pc,
                record.entry_rsp,
                record.return_word,
                generation,
                bits
            ]
        );
    }
    assert_eq!(&return_pcs, returns, "both original strnlen RETs exercised");
}
