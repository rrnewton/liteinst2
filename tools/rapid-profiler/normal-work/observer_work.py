#!/usr/bin/env python3
"""Strict fixed-population observer-work transcript; no duration estimator."""
import sys
if sys.flags.optimize:
    raise SystemExit('assertions required')
import re

U64 = (1 << 64)-1
U32 = (1 << 32)-1
ROWS = 3072
MAX_OUTPUT = 790528
MAX_ROW = 248
COMMENT = '# normal observer work; semantic counts and raw callback ticks only; no accuracy or performance claim'
HEADER = 'id,repetition,case,seed_index,length,input_fnv1a64,value,instructions,conditional,taken,input_bytes,ret_bytes,batch,owner,generation,invocation,history_prefix,entry_rsp,return_word,start_ticks,end_ticks,start_aux,end_aux,raw_ticks,ack,ack_ordinal'
FIELDS = tuple(HEADER.split(','))
WORK_FIELDS = ('instructions', 'conditional', 'taken', 'input_bytes', 'ret_bytes')
TERMINAL_KEYS = ('mode', 'selection', 'repetitions', 'calls', 'helper_calls',
    'instructions', 'conditional', 'taken', 'input_bytes', 'ret_bytes', 'pid', 'tid',
    'entry', 'caller', 'install', 'function', 'generation', 'batches', 'events',
    'reports', 'records', 'actions', 'journal_words', 'next_entry_acknowledgements',
    'checkpoint_acknowledgements', 'input_unchanged', 'joined')
SDK_COUNTS = ('batches', 'events', 'reports', 'records', 'actions', 'journal_words',
    'next_entry_acknowledgements', 'checkpoint_acknowledgements')
SCOPE = ('Finite functional population and original-body work only. Raw callback ticks '
    'are uncalibrated; zero and adverse spans are retained. No duration accuracy, '
    'performance, independent workload population, session-temporal or full-A5 claim.')
SOURCE_ATTESTED = ('Actual ordinary helper returns, independently trusted ELF/source/input '
    'and generated bytes, retained stack VMA/red-zone custody, all512 journal words '
    'per batch and full Report/history/receipt joins require producer source and '
    'separate execution authority. This compact transcript does not independently '
    'replay those checks; native rows contain no SDK or stack observation.')
UINT = re.compile(r'0|[1-9][0-9]{0,19}')
ASCII = re.compile(rb'[\x20-\x7e\n]+')


def _uint(text):
    assert type(text) is str and UINT.fullmatch(text)
    value = int(text)
    assert value <= U64
    return value


def _cases():
    # Independent input/scalar/work algebra, not observed candidate results.
    cases = []
    for seed in (0, 1):
        data = [(37*j+11+seed) % 256 for j in range(64)]
        digest = 14695981039346656037
        for byte in data:
            digest = ((digest ^ byte)*1099511628211) & U64
        for length in (1, 64):
            cases.append((seed, length, digest,
                sum(byte ^ 0x5a for byte in data[:length]) ^ 0x9e3779b97f4a7c15,
                6*length+5, length, length-1, length, 8))
    return tuple(cases)


def _terminal(line, mode):
    words = line.split(' ')
    assert words[:2] == ['normal-observer-work', 'FUNCTIONAL_PASS']
    assert len(words) == len(TERMINAL_KEYS)+2
    result = {}
    for name, word in zip(TERMINAL_KEYS, words[2:]):
        assert word.startswith(name+'=')
        text = word[len(name)+1:]
        if name in ('mode', 'selection'):
            result[name] = text
        elif name in ('input_unchanged', 'joined'):
            assert text == 'true'
            result[name] = True
        elif mode == 'native' and name in ('install', 'function', 'generation'):
            assert text == 'none'
            result[name] = None
        else:
            result[name] = _uint(text)
    assert result['mode'] == mode and result['selection'] == 'normal-exact-37-v1'
    assert (result['repetitions'], result['calls'], result['helper_calls']) == (128, ROWS, 1536)
    assert tuple(result[k] for k in WORK_FIELDS) == (614400, 99840, 96768, 99840, 24576)
    assert 0 < result['pid'] <= U32 and result['tid'] == result['pid']
    assert 0 < result['entry'] <= U64-37 and 0 < result['caller'] <= U64-67
    if mode == 'always-on':
        assert (result['install'], result['function']) == (1852793459, 1)
        assert result['generation'] > 0
        assert tuple(result[k] for k in SDK_COUNTS) == (128, 6144, 1, ROWS, 2, 65536, 2944, 128)
    else:
        assert all(result[k] == 0 for k in SDK_COUNTS)
    return result


def check(stdout, stderr, mode):
    assert type(mode) is str and mode in ('native', 'always-on')
    assert type(stdout) is bytes and 0 < len(stdout) <= MAX_OUTPUT
    assert type(stderr) is bytes and stderr == b''
    assert stdout.endswith(b'\n') and ASCII.fullmatch(stdout)
    lines = stdout[:-1].decode('ascii').split('\n')
    assert len(lines) == ROWS+3 and lines[:2] == [COMMENT, HEADER]
    assert sum(len(line)+1 for line in (lines[0], lines[1], lines[-1])) <= 4096
    terminal = _terminal(lines[-1], mode)
    cases = _cases()
    rows = []
    for g, line in enumerate(lines[2:-1]):
        assert len(line)+1 <= MAX_ROW
        cells = line.split(',')
        assert len(cells) == 26
        row = {}
        for name, cell in zip(FIELDS, cells):
            absent = (mode == 'native' and name in FIELDS[12:]) or (name == 'ack_ordinal' and g % 24 == 23)
            if absent:
                assert cell == ''
                row[name] = None
            elif name in ('owner', 'ack'):
                row[name] = cell
            else:
                row[name] = _uint(cell)
        expected = (g+1, g//24+1, g % 24+1, *cases[(g % 8)//2])
        assert tuple(row[name] for name in FIELDS[:12]) == expected
        if mode == 'always-on':
            assert (row['batch'], row['owner'], row['generation'], row['invocation'], row['history_prefix']) == (
                g//24+1, 'sampled', terminal['generation'], g, 1)
            rsp = row['entry_rsp']
            assert rsp % 16 == 8 and 128 <= rsp <= U64-8
            assert row['return_word'] == terminal['caller']+(30 if g % 2 == 0 else 48)
            start, end = row['start_ticks'], row['end_ticks']
            assert start <= end and row['raw_ticks'] == end-start
            assert row['start_aux'] == row['end_aux'] <= U32
            assert row['ack'] == ('C' if g % 24 == 23 else 'N')
            assert row['ack_ordinal'] == (None if g % 24 == 23 else g+2)
            if g % 2:
                assert rows[-1]['entry_rsp'] == rsp
        rows.append(row)
    totals = {name: sum(row[name] for row in rows) for name in WORK_FIELDS}
    assert totals == {name: terminal[name] for name in WORK_FIELDS}
    if mode == 'always-on':
        assert len({row['batch'] for row in rows}) == terminal['batches']
        assert sum(row['ack'] == 'N' for row in rows) == terminal['next_entry_acknowledgements']
        assert sum(row['ack'] == 'C' for row in rows) == terminal['checkpoint_acknowledgements']
    table = ('\n'.join(lines[1:-1])+'\n').encode('ascii')
    return dict(status='FUNCTIONAL_PASS', **terminal, totals=totals, rows=rows, table=table,
        zero_raw_spans=(sum(row['raw_ticks'] == 0 for row in rows) if mode == 'always-on' else None),
        scope=SCOPE, source_attested=SOURCE_ATTESTED)
