/* Private, unexecuted planner specimen. Calls the actual sealed decoder and
   planner; it does NOT execute generated bytes or qualify runtime ownership.
   Future owner: unchanged native 5 CPU / 15 wall / 512 MiB / 16 MiB limits. */
#include "region_plan.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static _Alignas(64) unsigned char arena[2U*1024U*1024U];
static _Alignas(64) unsigned char source[LI2_REGION_PAGE];
static struct li2_region_plan plan,changed;
static struct li2_decoder_stats initial;
static unsigned positives,refusals,corruptions,mapped,missed;
#define P UINT64_C(0x100000000)
#define G (P+UINT64_C(0x10000))
#define CHECK(x) do {if(!(x)){fprintf(stderr,"planner oracle line %u\n",__LINE__);exit(1);}} while(0)
_Noreturn void li2_decoder_abort(uint32_t reason) {
    fprintf(stderr,"actual decoder abort %u\n",reason);_Exit(125);
}
static void stats_equal(void) {
    struct li2_decoder_stats now;
    CHECK(li2_decoder_stats(&now)==LI2_OK);
    CHECK(!memcmp(&now,&initial,sizeof now));
}
static void input(const unsigned char *body,size_t n,unsigned offset) {
    CHECK(offset<=LI2_REGION_PAGE && n<=LI2_REGION_PAGE-offset);
    memset(source,0xcc,sizeof source);memcpy(source+offset,body,n);
}
static void positive(uintptr_t page,uintptr_t entry,uintptr_t generated,
                     unsigned heads,unsigned bytes,unsigned blocks,unsigned exits,
                     unsigned longest,unsigned image,unsigned stop) {
    CHECK(li2_region_plan_page(page,source,entry,generated,&plan)==LI2_REGION_PLAN_OK);
    CHECK(plan.ready==1 && plan.version==1 && plan.page==page && plan.entry==entry &&
          plan.generated==generated && plan.heads==heads && plan.source_bytes==bytes &&
          plan.boundary_pc==entry+bytes && plan.blocks==blocks && plan.exits==exits &&
          plan.longest_path==longest && plan.image_bytes==image && plan.stop_reason==stop);
    CHECK(plan.maps==heads+(plan.original[heads-1].flow!=LI2_REGION_JMP));
    CHECK(plan.decoder_calls==heads+1+plan.maps && !plan.decoder_result);
    CHECK(!memcmp(plan.source,source,sizeof source));
    CHECK(li2_region_plan_validate(&plan)==LI2_REGION_PLAN_OK);
    unsigned emitted=0;
    for(unsigned i=0;i<heads;i++) {
        const struct li2_region_decoded *d=&plan.original[i];
        struct li2_decoded old;
        CHECK(li2_decoder_decode(d->decoded.pc,source+plan.head[i].source_offset,
                                d->decoded.available,&old)==LI2_OK);
        CHECK(!memcmp(&old,&d->decoded,sizeof old)); /* old STEP stays exact */
        CHECK(plan.head[i].generated_offset==emitted);
        unsigned n=d->flow==LI2_REGION_NEXT?old.length:d->flow==LI2_REGION_JCC?6:5;
        CHECK(plan.head[i].generated_length==n);
        if(d->flow==LI2_REGION_NEXT)
            CHECK(!memcmp(plan.image+emitted,source+plan.head[i].source_offset,n));
        else CHECK(plan.image[emitted]==(d->flow==LI2_REGION_JCC?0x0f:0xe9));
        emitted+=n;
    }
    CHECK(emitted+(plan.maps>heads?5:0)==image);
    for(unsigned i=image;i<LI2_REGION_PAGE;i++)CHECK(plan.image[i]==0xcc);
    /* Every byte of the emitted body: exact heads succeed, all interior
       bytes refuse. Tail/underflow are separately checked below. */
    for(unsigned at=0;at<image;at++) {
        unsigned row=0;while(row<plan.maps && plan.map[row].generated_offset!=at)row++;
        struct li2_region_pc pc,empty={0};
        int e=li2_region_map_pc(&plan,generated+at,&pc);
        if(row==plan.maps){CHECK(e==LI2_REGION_PLAN_MISS && !memcmp(&pc,&empty,sizeof pc));missed++;}
        else {
            CHECK(e==0 && pc.ready==1 && pc.version==1 && pc.generated_pc==generated+at);
            unsigned tail=row==heads,head=tail?heads-1:row;
            CHECK(pc.head_index==head && pc.source_offset==
                  (tail?entry-page+bytes:plan.head[head].source_offset));
            CHECK(pc.original_pc==page+pc.source_offset && pc.generated_offset==at &&
                  pc.generated_length==(tail?5:plan.head[head].generated_length) &&
                  pc.source_length==(tail?0:plan.head[head].source_length));
            CHECK(pc.kind==(tail?LI2_REGION_PC_EXIT:plan.original[head].flow==LI2_REGION_NEXT?
                            LI2_REGION_PC_COPIED:LI2_REGION_PC_BRANCH));mapped++;
        }
    }
    const uintptr_t outside[]={generated-1,generated+image,generated+4095,generated+4096};
    for(unsigned i=0;i<4;i++) {
        struct li2_region_pc pc,empty={0};
        CHECK(li2_region_map_pc(&plan,outside[i],&pc)==LI2_REGION_PLAN_MISS &&
              !memcmp(&pc,&empty,sizeof pc));missed++;
    }
    stats_equal();positives++;
}
static void refuse(uintptr_t page,uintptr_t entry,uintptr_t generated,int want) {
    memset(&changed,0xa5,sizeof changed);
    CHECK(li2_region_plan_page(page,source,entry,generated,&changed)==want && !changed.ready);
    stats_equal();refusals++;
}
static void graph_cases(void) {
    static const unsigned char linear[]={0x48,0x89,0xd8,0x0f,0xa2};
    static const unsigned char diamond[]={0x48,0x85,0xc0,0x74,5,0x48,0x89,0xd9,
        0xeb,3,0x48,0x89,0xd1,0x48,0x85,0xc9,0x0f,0xa2};
    static const unsigned char backward[]={0xeb,2,0xeb,2,0xeb,0xfc,0x0f,0xa2};
    static const unsigned char duplicate[]={0x74,0,0x89,0xc0,0x0f,0xa2};
    input(linear,sizeof linear,0);positive(P,P,G,1,3,1,1,1,8,1);
    input(diamond,sizeof diamond,0);positive(P,P,G,6,16,4,1,5,28,1);
    input(backward,sizeof backward,0);positive(P,P,G,3,6,3,1,3,15,1);
    input(duplicate,sizeof duplicate,0);positive(P,P,G,2,4,2,1,2,13,1);
    unsigned char body[300];memset(body,0xcc,sizeof body);
    for(unsigned i=0;i<65;i++){body[2*i]=0x89;body[2*i+1]=0xc0;}
    input(body,130,0);positive(P,P,G,64,128,1,1,64,133,LI2_REGION_STOP_HEADS);
    const unsigned char load[8]={0x48,0x8b,0x84,0x24,0,0,0,0};
    for(unsigned i=0;i<33;i++)memcpy(body+8*i,load,8);
    input(body,264,0);positive(P,P,G,32,256,1,1,32,261,LI2_REGION_STOP_BYTES);
    const unsigned char load32[7]={0x8b,0x84,0x24,0,0,0,0};
    memcpy(body+248,load32,7);body[255]=0x89;body[256]=0xc0;
    input(body,257,0);positive(P,P,G,32,255,1,1,32,260,LI2_REGION_STOP_BYTES);
    for(unsigned i=0;i<7;i++){body[2*i]=0x74;body[2*i+1]=(unsigned char)(16-2*i-2);}
    body[14]=0x89;body[15]=0xc0;body[16]=0x0f;body[17]=0xa2;
    input(body,18,0);positive(P,P,G,8,16,8,1,8,49,1);
    for(unsigned i=0;i<8;i++){body[2*i]=0x74;body[2*i+1]=(unsigned char)(32+2*(i%7)-2*i-2);}
    body[16]=0x0f;body[17]=0xa2;
    input(body,18,0);positive(P,P,G,8,16,8,8,8,53,1);
    /* Same eight blocks, but nine distinct exits: isolate the exit cap. */
    body[15]=(unsigned char)(46-16);input(body,18,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    /* Nine blocks, one exit: isolate the block cap. */
    for(unsigned i=0;i<8;i++){body[2*i]=0x74;body[2*i+1]=(unsigned char)(18-2*i-2);}
    body[16]=0x89;body[17]=0xc0;body[18]=0x0f;body[19]=0xa2;
    input(body,20,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    const unsigned char self[]={0x74,0xfe,0x89,0xc0,0x0f,0xa2};
    const unsigned char cycle[]={0xeb,0,0xeb,0xfc,0x0f,0xa2};
    const unsigned char interior[]={0x74,1,0x48,0x89,0xd8,0x0f,0xa2};
    const unsigned char unreachable[]={0xeb,3,0x48,0x89,0xc0,0x48,0x89,0xd8,0x0f,0xa2};
    const unsigned char crosspage[]={0xe9,0xfb,0x0f,0,0,0x0f,0xa2};
    input(self,sizeof self,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    input(cycle,sizeof cycle,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    input(interior,sizeof interior,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    input(unreachable,sizeof unreachable,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    input(crosspage,sizeof crosspage,0);refuse(P,P,G,LI2_REGION_PLAN_GRAPH);
    const unsigned char unsupported[]={0x0f,0xa2};
    input(unsupported,2,0);refuse(P,P,G,LI2_REGION_PLAN_MISS);
    const unsigned char truncated[]={0x0f};
    input(truncated,1,4095);refuse(P,P+4095,G,LI2_REGION_PLAN_BOUNDARY);
    const unsigned char end[]={0x89,0xc0};
    input(end,2,4094);refuse(P,P+4094,G,LI2_REGION_PLAN_BOUNDARY);
}
static void rel32_cases(void) {
    const unsigned char linear[]={0x48,0x89,0xd8,0x0f,0xa2};
    const unsigned char jump[]={0xeb,2,0x0f,0xa2};
    /* Exact signed limits and one beyond; virtual addresses describe bytes,
       never assert these test pages are mapped or executable. */
    input(linear,5,4);positive(P,P+4,P-0x80000000ULL,1,3,1,1,1,8,1);
    input(linear,5,5);refuse(P,P+5,P-0x80000000ULL,LI2_REGION_PLAN_RELOCATION);
    input(linear,5,5);positive(P,P+5,P+0x80000000ULL,1,3,1,1,1,8,1);
    input(linear,5,4);refuse(P,P+4,P+0x80000000ULL,LI2_REGION_PLAN_RELOCATION);
    input(jump,4,0);positive(P,P,P-0x80000000ULL,1,2,1,1,1,5,1);
    input(jump,4,1);refuse(P,P+1,P-0x80000000ULL,LI2_REGION_PLAN_RELOCATION);
    input(jump,4,1);positive(P,P+1,P+0x80000000ULL,1,2,1,1,1,5,1);
    input(jump,4,0);refuse(P,P,P+0x80000000ULL,LI2_REGION_PLAN_RELOCATION);
    unsigned char jcc[]={0x74,3,0xeb,0,0x0f,0xa2};
    input(jcc,6,0);positive(P,P,P-0x80000000ULL,2,4,2,2,2,11,1);
    jcc[1]=4;input(jcc,6,0);refuse(P,P,P-0x80000000ULL,LI2_REGION_PLAN_RELOCATION);
    jcc[3]=9;input(jcc,6,0);positive(P,P,P+0x80000000ULL,2,4,2,2,2,11,1);
    jcc[1]=3;input(jcc,6,0);refuse(P,P,P+0x80000000ULL,LI2_REGION_PLAN_RELOCATION);
}
static void real77(void) {
    /* Retained interpreter SHA34c23201; original [b5f2,b63f) SHA552ae166.
       The following genuine 6-byte RIP-relative boundary is unsupported.
       Surrounding CC makes this a planner specimen, not a full live-page lease. */
    const unsigned char body[]={
        0x48,0x89,0xc8,0x48,0x85,0xd2,0x0f,0x84,0x40,0x01,0x00,0x00,0x48,0x85,0xc9,0x74,0x0b,
        0x0f,0xb6,0x41,0x05,0x83,0xe0,0x03,0x3c,0x03,0x74,0x62,0x4c,0x8b,0x7c,0x24,0x58,
        0x31,0xdb,0x41,0x0f,0xb6,0x87,0x1c,0x03,0x00,0x00,0x83,0xe0,0x03,0x3c,0x02,0x0f,
        0x84,0xec,0x03,0x00,0x00,0x4c,0x8b,0x54,0x24,0x50,0x4d,0x89,0xfd,0x41,0x8b,0xbf,
        0xe4,0x03,0x00,0x00,0x85,0xff,0x0f,0x84,0xd9,0x01,0x00,0x00,0x8b,0x05,0xbb,0xd4,0x02,0x00};
    static const unsigned offsets[]={0,3,6,12,15,17,21,24,26,28,33,35,43,46,48,54,59,62,69,71};
    static const unsigned lengths[]={3,3,6,3,2,4,3,2,2,5,2,8,3,2,6,5,3,7,2,6};
    static const unsigned exits[]={0x73e,0x670,0xa14,0x818,0x63f};
    input(body,sizeof body,0x5f2);positive(P,P+0x5f2,G,20,77,5,5,20,90,1);
    CHECK(plan.maps==21 && plan.decoder_calls==42);
    for(unsigned i=0;i<20;i++)CHECK(plan.head[i].source_offset==0x5f2+offsets[i] &&
                                   plan.head[i].source_length==lengths[i]);
    for(unsigned i=0;i<5;i++)CHECK(plan.exit_pc[i]==P+exits[i]);
    unsigned loads=0;for(unsigned i=0;i<20;i++)loads+=plan.original[i].memory_count;
    CHECK(loads==5);
}
static void argument_and_corruption(void) {
    const uintptr_t bad_page[]={P+1,UINT64_C(0x800000000000),UINT64_MAX-4095};
    for(unsigned i=0;i<3;i++)refuse(bad_page[i],bad_page[i],G,LI2_REGION_PLAN_ARGUMENT);
    refuse(P,P,G+1,LI2_REGION_PLAN_ARGUMENT);refuse(P,P,P,LI2_REGION_PLAN_ARGUMENT);
    refuse(P,P-1,G,LI2_REGION_PLAN_ARGUMENT);refuse(P,P+4096,G,LI2_REGION_PLAN_ARGUMENT);
    CHECK(li2_region_plan_page(P,source,P,G,NULL)==LI2_REGION_PLAN_ARGUMENT);refusals++;
    CHECK(li2_region_map_pc(NULL,G,(struct li2_region_pc *)&changed)==LI2_REGION_PLAN_ARGUMENT);refusals++;
    CHECK(li2_region_map_pc(&plan,G,NULL)==LI2_REGION_PLAN_ARGUMENT);refusals++;
    CHECK(li2_region_map_pc(&plan,G,(struct li2_region_pc *)&plan)==LI2_REGION_PLAN_ARGUMENT);refusals++;
#define CORRUPT(edit) do {changed=plan;edit;CHECK(li2_region_plan_validate(&changed)==LI2_REGION_PLAN_CORRUPT);corruptions++;} while(0)
    CORRUPT(changed.version++);CORRUPT(changed.ready=0);CORRUPT(changed.heads--);
    CORRUPT(changed.blocks++);CORRUPT(changed.exits--);CORRUPT(changed.maps--);
    CORRUPT(changed.longest_path--);CORRUPT(changed.decoder_calls--);
    CORRUPT(changed.decoder_result=1);CORRUPT(changed.source_bytes--);
    CORRUPT(changed.image_bytes--);CORRUPT(changed.stop_reason++);
    CORRUPT(changed.source[0x5f2]^=1);CORRUPT(changed.image[0]^=1);
    CORRUPT(changed.image[4095]^=1);CORRUPT(changed.original[0].decoded.step_disposition++);
    CORRUPT(changed.original[63].version=1);CORRUPT(changed.emitted[64].ready=1);
    CORRUPT(changed.boundary.decoded.code++);CORRUPT(changed.exit_pc[7]=P);
    CORRUPT(changed.head[0].successors[0]++);CORRUPT(changed.map[0].original_pc++);
    CORRUPT(changed.map[64].ready=1);
#undef CORRUPT
    stats_equal();
}
int main(void) {
    CHECK(li2_decoder_initialize(arena,sizeof arena,&initial)==LI2_OK &&
          initial.abi_version==1 && initial.phase==2 && !initial.first_fatal_reason &&
          !initial.reserved && initial.arena_bytes==sizeof arena &&
          initial.retained_high_water && initial.retained_high_water<=sizeof arena);
    graph_cases();rel32_cases();real77();argument_and_corruption();stats_equal();
    CHECK(positives==16 && refusals==27 && corruptions==23 && mapped==195 && missed==827);
    printf("{\"version\":1,\"planner_only\":1,\"positive\":%u,\"refused\":%u,"
           "\"corrupt\":%u,\"mapped\":%u,\"interior_or_outside\":%u,\"postseal_equal\":1}\n",
           positives,refusals,corruptions,mapped,missed);
    return 0;
}
