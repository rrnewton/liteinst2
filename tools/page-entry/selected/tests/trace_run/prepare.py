#!/usr/bin/env python3
"""Generate only the reviewed generic dump delegation for the additive TRACE entry fixture."""
import argparse
import hashlib
import json
from pathlib import Path

SOURCE_SHA256 = 'b0c758cb466ef3f8a35442f7cecbda77eb58c269a7ac90270d769c53440b2910'
GENERATED_SHA256 = '3d096f10d66d1ee6e6d665d4aaefb4e3f2f78c62287942d8db81e3be3130b3b6'
OLD = b'static int dump(void) {\n    result.header_bytes=sizeof(result);result.sample_bytes=sizeof(struct sample);\n    return write_all(3,&result,sizeof(result)) && write_all(3,samples,sizeof(samples)) &&\n           write_all(3,&negative_sample,sizeof(negative_sample)) && write_all(3,&refused_last,sizeof(refused_last));\n}'
NEW = b'static int dump(void) { return tr_dump(); }'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    before = args.source.read_bytes()
    if hashlib.sha256(before).hexdigest() != SOURCE_SHA256 or before.count(OLD) != 1:
        raise ValueError('exact unchanged generic fixture required')
    generated = before.replace(OLD, NEW)
    if hashlib.sha256(generated).hexdigest() != GENERATED_SHA256:
        raise ValueError('exact reviewed generated support required')
    with args.output.open('xb') as output:
        output.write(generated)
    if args.source.read_bytes() != before or args.output.read_bytes() != generated:
        raise ValueError('source/generated bytes changed')
    print(json.dumps({'source_sha256': SOURCE_SHA256,
                      'generated_sha256': GENERATED_SHA256,
                      'source_bytes': len(before), 'generated_bytes': len(generated)},
                     sort_keys=True, separators=(',', ':')))


if __name__ == '__main__':
    main()
