static void modeled_routes(void) {
    uint64_t raw[16];for(unsigned i=0;i<16;i++)raw[i]=UINT64_C(0x1234567800000000)+0x101*i;
    for(unsigned mode=0;mode<3;mode++)for(unsigned member=0;member<5;member++) {
        struct li2_dd_plan direct;const struct li2_dd_plan *p;
        if(member<3) {
            const unsigned who=member!=0,head=member==0?2:member==1?3:4;
            assert(!li2_lpf_compact_direct(&publication[who].value.plan,0,head,&direct));p=&direct;
        } else {active=&images[member-3].plan;p=&active->value;}
        model_directory=directory;
        if(mode==1)model_directory.count=8; /* original heads, no auxiliary rows */
        if(mode==2)model_directory.count=0;
        uint64_t visited=0;
        for(unsigned f=0;f<64;f++) {
            struct dd_model_result out;uint64_t before=decoded;
            assert(!lcx_model_run(p,&model_directory,raw,flags_for(f),&out) && decoded==before &&
                out.steps==out.recoveries && out.steps>0);
            if(member==1 && !dd_model_taken(5,flags_for(f)))
                assert(out.internal && !out.hit && !out.miss && out.target==layouts[1].generated[0]+4*512);
            else if(member==2 || mode==2 || (mode==1 && member<2))
                assert(out.miss && !out.hit && !out.internal && out.target==p->original.decoded.pc && !out.cell_writes);
            else {
                uintptr_t target=member<2?AUX_CODE+512*member:layouts[4-member].generated[0];
                assert(out.hit && !out.miss && !out.internal && out.target==target && out.cell_writes==1);
            }
            visited|=out.visited;steps+=out.steps;if(member>=3)aux_steps+=out.steps;++models;
        }
        if(mode==0 && member>=3)assert(visited && p->record.boundaries==37);
        active=0;
    }
    assert(models==960 && aux_steps>384 && recoveries==2*aux_steps);
}
