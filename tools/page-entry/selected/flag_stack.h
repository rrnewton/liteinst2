#ifndef LI2_FLAG_STACK_H
#define LI2_FLAG_STACK_H
#include "decoder.h"
#include "write_footprint.h"

#define LI2_FS_VERSION 1U
#define LI2_FS_IMAGE_BYTES 16U
enum li2_fs_operation { LI2_FS_UNSUPPORTED=0,LI2_FS_PUSHFQ=1,LI2_FS_POPFQ=2 };
enum li2_fs_status { LI2_FS_OK=0,LI2_FS_ARGUMENT=5101,LI2_FS_FORM=5102,
    LI2_FS_DECODER=5103,LI2_FS_CORRUPT=5104 };
struct li2_fs_descriptor {
    struct li2_decoded decoded;
    uint32_t version,operation;
};
/* Descriptive only. All arguments are distinct live owned buffers. The sealed
   decoder and complete independent literal reconstruction must agree. Neither
   a descriptor nor the generated bytes grant source, stack, RX, rseq, signal,
   lifetime, or continuation authority. Old TF classification remains zero. */
int li2_fs_describe(uintptr_t,const unsigned char *,size_t,struct li2_fs_descriptor *);
int li2_fs_validate(const struct li2_fs_descriptor *);
/* Exact 9c/9d; FF25 disp32=1; CC pad; aligned original-next literal. The owner
   places the image at an eight-byte-aligned address and proves original-next
   NX before entry. No GPR/stack scratch, TF injection or rel32 target limit. */
int li2_fs_emit(const struct li2_fs_descriptor *,unsigned char[LI2_FS_IMAGE_BYTES]);
/* PUSH has its complete potential eight-byte store; POP has no application
   write. Underflow/overflow returns UNSUPPORTED with zero endpoints. This
   separate description does not broaden the TF-bound footprint API. */
int li2_fs_write(const struct li2_fs_descriptor *,uint64_t,struct li2_write_footprint *);
_Static_assert(sizeof(struct li2_fs_descriptor)==80,"whole flag-stack descriptor");
_Static_assert(_Alignof(struct li2_fs_descriptor)==8,"flag-stack descriptor alignment");
_Static_assert(offsetof(struct li2_fs_descriptor,version)==72,"flag-stack version offset");
#endif
