def _load(name, path, pin):
    spec = importlib.util.spec_from_file_location(name, pin(path))
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def _observed(prepare, selected, output, pin, binary, **config):
    """Read the complete declared view; compose() verifies whole-file inverses."""
    old = prepare.original(ROOT, pin)
    leaf = selected / 'tests/page_custody'
    facts = []

    def check(name, original, data):
        actual = pin(binary(output / name))
        need(actual.read_bytes() == data, 'complete actual custody generated bytes: ' + name)
        facts.append(dict(name=name, before=None if original is None else fact(original),
                          after=fact(actual)))

    for name in prepare.FILES:
        original = pin(selected / name)
        check(name, original, prepare.compose(name, original.read_bytes(), old))
    original = pin(selected / 'tests/tf_same_page/observe.inc')
    check('tf_lease_observe.inc', original,
          prepare.compose('tf_lease_observe.inc', original.read_bytes(), old))
    original = pin(selected / 'tests/tf_same_page/record.h')
    before = original.read_bytes()
    a, b = b'#include "../rseq_native/record.h"', b'#include "tf_lease_old_record.h"'
    need(before.count(a) == 1 and b not in before, 'exact original frame include')
    transformed = before.replace(a, b)
    need(transformed.replace(b, a) == before, 'complete frame include inverse')
    check('tf_lease_record.h', original, transformed)
    for source, name in ((selected / 'tests/rseq_native/record.h', 'tf_lease_old_record.h'),
                         (selected / 'tf_same_page.h', 'tf_lease_types.h'),
                         (leaf / 'record.h', 'page_custody_record.h'),
                         (leaf / 'observe.inc', 'page_custody_observe.inc')):
        original = pin(source)
        check(name, original, original.read_bytes())
    check('page_custody_config.h', None, prepare.config(**config))
    return facts


